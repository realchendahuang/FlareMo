/**
 * 把 src/client/ 打成 DSH 客户端加载器认的浏览器产物：
 *
 *   window.__ModuleLoader__.load({
 *     id: "dsh-flaremo",
 *     factory(require) { var module = { exports: {} }; var exports = module.exports;
 *       /* esbuild 的 CJS 产物 *_/
 *       return module.exports;
 *     },
 *   });
 *
 * 为什么是 CJS + factory：浏览器内核把每个插件 bundle 注册成 factory，
 * `require('react')` 等由宿主冻结的模块表解析，所以 React 必须 external。
 *
 * 产物两份：
 *   dist/client.bundle.cjs  中间产物（未包装，.gitignore 掉了）
 *   dist/client.js          随包发布、提交进仓库的产物（package.json 的 ./client 指向它）
 *
 * 运行：node scripts/build-client.mjs
 */

import { build, version as esbuildVersion } from 'esbuild'
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const BUNDLE_PATH = resolve(ROOT, 'dist', 'client.bundle.cjs')
export const CLIENT_PATH = resolve(ROOT, 'dist', 'client.js')

const WRAPPER_HEADER = '/** Generated by scripts/build-client.mjs — do not edit by hand. */'

/**
 * esbuild 选项。`external` 只列宿主共享模块表里有的模块：
 * react 走 external；本插件没有别的共享表依赖，所以清单就这一个。
 */
const BUILD_OPTIONS = {
  absWorkingDir: ROOT,
  entryPoints: [resolve(ROOT, 'src/client/entry.jsx')],
  bundle: true,
  format: 'cjs', // ← 必须是 CJS：factory(require) 按 CJS 解释
  platform: 'browser',
  target: ['es2020'],
  jsx: 'transform', // 经典运行时：JSX → React.createElement
  external: ['react'],
  // Geist Variable 的 latin 子集（29KB woff2）以 data URI 打进 bundle：
  // 客户端插件没有独立的资源路由，字体必须自包含（见 theme.js 的 @font-face）。
  loader: { '.woff2': 'dataurl' },
  minify: true,
  charset: 'utf8', // 中文保持原字符，不转 \uXXXX
  logLevel: 'silent',
}

/**
 * 把 esbuild 的 CJS 产物包进加载器 factory。
 * @param {string} code - the raw CJS bundle.
 * @param {string} pkgName - package name, used as the loader entry id.
 * @returns {string} the full dist/client.js text.
 */
export function wrapBundle(code, pkgName) {
  // ⚠️ 不要给 code 的每一行补缩进：esbuild 的 minify 会把 "\n" 字符串压成
  // 内含真实换行的模板字面量（`<换行>`），逐行重排会把包装器的缩进空格写进
  // 字符串值里 —— 2026-11-08 这 bug 把 markdown 解析器的 replace(/\r\n?/g, "\n")
  // 变成 replace(..., "\n    ")，整篇正文退化成单个段落。原样嵌入最安全。
  return `${WRAPPER_HEADER}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkgName)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  },
});
`
}

/**
 * 在内存里构建并返回两份文本，不碰磁盘（留给将来做防漂移检查）。
 * @param {{ pkg?: object }} [options] - optional manifest override.
 * @returns {Promise<{ bundle: string, wrapper: string, pkg: object }>} build output.
 */
export async function renderClient({ pkg } = {}) {
  const manifest = pkg ?? JSON.parse(await readFile(resolve(ROOT, 'package.json'), 'utf8'))
  const result = await build({ ...BUILD_OPTIONS, outfile: BUNDLE_PATH, write: false })
  const [output] = result.outputFiles
  return { bundle: output.text, wrapper: wrapBundle(output.text, manifest.name), pkg: manifest }
}

/**
 * 构建并落盘：dist/client.bundle.cjs（中间产物）+ dist/client.js（发布产物）。
 * client.js 用「写临时文件再 rename」保证不会写出半个文件。
 * @returns {Promise<{ bytes: number, pkg: object }>} artifact size and manifest.
 */
export async function writeClient() {
  const { bundle, wrapper, pkg } = await renderClient()

  await mkdir(dirname(BUNDLE_PATH), { recursive: true })
  await writeFile(BUNDLE_PATH, bundle, 'utf8')

  const tmpPath = `${CLIENT_PATH}.tmp-${process.pid}`
  try {
    await writeFile(tmpPath, wrapper, 'utf8')
    await rename(tmpPath, CLIENT_PATH)
  } catch (error) {
    await rm(tmpPath, { force: true })
    throw error
  }

  const bytes = Buffer.byteLength(wrapper)
  console.log(
    `dist/client.js written (${bytes} bytes, esbuild ${esbuildVersion}, ${pkg.name}@${pkg.version})`,
  )
  return { bytes, pkg }
}

const invokedDirectly =
  process.argv[1] !== undefined && pathToFileURL(resolve(process.argv[1])).href === import.meta.url

if (invokedDirectly) {
  try {
    await writeClient()
  } catch (error) {
    console.error('client build failed:', error)
    process.exitCode = 1
  }
}
