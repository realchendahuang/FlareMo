/**
 * 产物形状检查：确认 dist/client.js 是加载器能吃的 wrapper，而不是裸的 esbuild 产物。
 *
 * 这一步不做字节级防漂移（那要把 BUILD_OPTIONS 再跑一遍），只做「产物还在、
 * id 对、factory 在、CJS 收尾在」四条硬检查 —— 足够拦住最常见的构建事故。
 *
 * 运行：node scripts/check-client.mjs
 */

import { readFileSync, statSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const CLIENT_PATH = resolve(ROOT, 'dist', 'client.js')

const problems = []

let text = ''
try {
  const info = statSync(CLIENT_PATH)
  if (info.size === 0) problems.push('dist/client.js 是空文件')
  text = readFileSync(CLIENT_PATH, 'utf8')
} catch {
  problems.push('dist/client.js 不存在，先跑 node scripts/build-client.mjs')
}

if (text !== '') {
  if (!text.startsWith('/** Generated by scripts/build-client.mjs')) {
    problems.push('dist/client.js 缺少构建头注释（可能被手改过）')
  }
  if (!text.includes('window.__ModuleLoader__.load({')) {
    problems.push('dist/client.js 没有 window.__ModuleLoader__.load({ 包裹')
  }
  if (!text.includes('id: "dsh-flaremo"')) {
    problems.push('dist/client.js 的 id 不是 "dsh-flaremo"（应来自 package.json name）')
  }
  if (!text.includes('factory(require) {')) {
    problems.push('dist/client.js 缺少 factory(require) 函数')
  }
  if (!text.includes('var module = { exports: {} };')) {
    problems.push('dist/client.js 缺少 CJS 的 module/exports 垫片')
  }
  if (!text.includes('return module.exports;')) {
    problems.push('dist/client.js 的 factory 没有 return module.exports')
  }
  if (!text.trimEnd().endsWith('});')) {
    problems.push('dist/client.js 没有以 }); 收尾')
  }
  if (text.length < 1024) {
    problems.push(`dist/client.js 只有 ${text.length} 字符，疑似构建不完整`)
  }
}

if (problems.length > 0) {
  for (const problem of problems) console.error(`✗ ${problem}`)
  process.exitCode = 1
} else {
  console.log(`✓ dist/client.js 形状正常（${Buffer.byteLength(text)} bytes）`)
}
